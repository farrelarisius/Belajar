-- =====================================================
-- TABEL DAFTAR KATEGORI BAWAAN (SUPABASE)
-- =====================================================

-- 1. Buat tabel kategori
CREATE TABLE IF NOT EXISTS public.kategori (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Aktifkan Row Level Security (RLS)
ALTER TABLE public.kategori ENABLE ROW LEVEL SECURITY;

-- 3. Kebijakan RLS: Izinkan siapa saja (publik / anon) membaca tabel kategori
DROP POLICY IF EXISTS "Izinkan akses baca publik untuk kategori" ON public.kategori;
CREATE POLICY "Izinkan akses baca publik untuk kategori" 
ON public.kategori 
FOR SELECT 
TO public 
USING (true);

-- 4. Kebijakan RLS: Izinkan tambah kategori (jika diperlukan)
DROP POLICY IF EXISTS "Izinkan insert kategori untuk publik" ON public.kategori;
CREATE POLICY "Izinkan insert kategori untuk publik" 
ON public.kategori 
FOR INSERT 
TO public 
WITH CHECK (true);

