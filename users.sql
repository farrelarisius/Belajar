-- =====================================================
-- TABEL PENGGUNA / REGISTRASI AKUN (SUPABASE)
-- =====================================================

-- 1. Buat tabel users
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    username TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Aktifkan Row Level Security (RLS)
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- 3. Kebijakan RLS: Izinkan siapa saja (publik / anon key) mendaftar (INSERT)
DROP POLICY IF EXISTS "Izinkan registrasi publik untuk users" ON public.users;
CREATE POLICY "Izinkan registrasi publik untuk users" 
ON public.users 
FOR INSERT 
TO public 
WITH CHECK (true);

-- 4. Kebijakan RLS: Izinkan siapa saja (publik / anon key) membaca data users untuk login (SELECT)
DROP POLICY IF EXISTS "Izinkan baca publik untuk users" ON public.users;
CREATE POLICY "Izinkan baca publik untuk users" 
ON public.users 
FOR SELECT 
TO public 
USING (true);

